import fs from "node:fs";
import path from "node:path";
import { StringDecoder } from "node:string_decoder";
import { RosterName } from "../../src/types/Team";

const DIVISIONS = new Set(["Competitive", "Blackbox", "Ranked", "League"]);

const FUMBBL_NAMES: Partial<Record<RosterName, string>> = {
  [RosterName.BRETONIAN]: "Bretonnian",
  [RosterName.SHAMBLING_UNDEAD]: "Shambling Undead",
};

interface CsvState {
  row: string[];
  field: string;
  quoted: boolean;

  pendingQuote: boolean;
}

function feedChar(state: CsvState, char: string): string[] | null {
  if (state.pendingQuote) {
    state.pendingQuote = false;
    if (char === '"') {
      state.field += '"';
      return null;
    }
    state.quoted = false;
  }
  if (state.quoted) {
    if (char === '"') state.pendingQuote = true;
    else state.field += char;
  } else if (char === '"') state.quoted = true;
  else if (char === ",") {
    state.row.push(state.field);
    state.field = "";
  } else if (char === "\n") {
    const row = state.row;
    row.push(state.field.replace(/\r$/, ""));
    state.row = [];
    state.field = "";
    return row;
  } else state.field += char;
  return null;
}

function* csvRows(file: string): Generator<string[]> {
  const fd = fs.openSync(file, "r");
  const buffer = Buffer.alloc(1 << 20);

  const decoder = new StringDecoder("utf8");
  const state: CsvState = {
    row: [],
    field: "",
    quoted: false,
    pendingQuote: false,
  };
  let read: number;
  while ((read = fs.readSync(fd, buffer, 0, buffer.length, null)) > 0) {
    const text = decoder.write(buffer.subarray(0, read));
    for (const char of text) {
      const row = feedChar(state, char);
      if (row) yield row;
    }
  }
  fs.closeSync(fd);
  if (state.field || state.row.length > 0) yield [...state.row, state.field];
}

function* records(file: string): Generator<Record<string, string>> {
  const rows = csvRows(file);
  const header = rows.next().value as string[];
  for (const row of rows)
    yield Object.fromEntries(header.map((name, i) => [name, row[i] ?? ""]));
}

const cell = (record: Record<string, string>, name: string): string =>
  record[name] ?? "";

const folder = process.argv[2];
if (!folder) {
  process.stderr.write(
    "usage: race-rates.ts <folder with the unzipped CSVs>\n"
  );
  process.exit(1);
}
const MAX_TEAM_VALUE = 1300;
const MIN_GAMES = 500;

const conceded = new Set<string>();
const matchesFile = path.join(folder, "df_matches.csv");
for (const match of records(matchesFile))
  if (match["match_conceded"] && match["match_conceded"] !== "None")
    conceded.add(cell(match, "match_id"));

const COLUMNS = {
  wins: "wins",
  touchdowns: "team_score",
  casualties: "home_cas",
  completions: "home_comp",
  blocks: "home_block",
} as const;
type Rate = keyof typeof COLUMNS;

const totals = new Map<string, { games: number } & Record<Rate, number>>();
const mbtFile = path.join(folder, "df_mbt.csv");
for (const row of records(mbtFile)) {
  if (
    conceded.has(cell(row, "match_id")) ||
    !DIVISIONS.has(cell(row, "division_name"))
  )
    continue;
  if (row["mirror_match"] === "1" || Number(row["team_value"]) > MAX_TEAM_VALUE)
    continue;
  const bucket = totals.get(cell(row, "race_name")) ?? {
    games: 0,
    wins: 0,
    touchdowns: 0,
    casualties: 0,
    completions: 0,
    blocks: 0,
  };
  bucket.games++;
  for (const [rate, column] of Object.entries(COLUMNS) as [Rate, string][])
    bucket[rate] += Number(row[column]) || 0;
  totals.set(cell(row, "race_name"), bucket);
}

const round = (x: number) => Math.round(x * 1000) / 1000;
const entries = Object.entries(RosterName).flatMap(
  ([key, roster]) => {
    const name = FUMBBL_NAMES[roster] ?? roster;
    const bucket = totals.get(name);
    if (!bucket || bucket.games < MIN_GAMES) {
      if (roster === RosterName.NIGHT_GOBLIN || roster === RosterName.WITCH_ELF) return [];
      throw new Error(`no FUMBBL rates for ${roster} (looked for "${name}")`);
    }
    const per = (rate: Rate) => round(bucket[rate] / bucket.games);
    return (
      `  [RosterName.${key}]: { games: ${String(bucket.games)}, wins: ${String(per("wins"))}, ` +
      `touchdowns: ${String(per("touchdowns"))}, casualties: ${String(per("casualties"))}, ` +
      `completions: ${String(per("completions"))}, blocks: ${String(per("blocks"))} },`
    );
  }
);

